// 4. Sentiment Analyzer & Literary Lexicon Tests
// ---------------------------------------------------------------------------
console.log('\nTest 4: Sentiment Analyzer & Aspect Extraction');
{
  // 4.1 Positive Review
  const pos = analyzeReviewSentiment('An absolute masterpiece! Breathtaking world-building and unputdownable fast-paced plot.', 5);
  assert(pos.score >= 0.20, `Expected positive score >= 0.20, got: ${pos.score}`);
  assert.equal(pos.label, 'positive');
  assert.equal(pos.classification, 'positive');
  assert.equal(pos.score, pos.polarity, 'Dual field score === polarity');
  assert(pos.aspects.includes('world-building'), `Expected world-building aspect, got: ${pos.aspects}`);
  assert(pos.aspects.includes('fast-paced'), `Expected fast-paced aspect, got: ${pos.aspects}`);
  assert(pos.keywords.includes('masterpiece'), `Expected masterpiece in keywords, got: ${pos.keywords}`);

  // 4.2 Negative Review
  const neg = analyzeReviewSentiment('Terrible disaster. Plodding, slow-dragging narrative and flat characters.', 1);
  assert(neg.score <= -0.20, `Expected negative score <= -0.20, got: ${neg.score}`);
  assert.equal(neg.label, 'negative');
  assert.equal(neg.classification, 'negative');
  assert(neg.aspects.includes('slow-dragging') || neg.aspects.includes('flat-characters'));

  // 4.3 Negation Inversion (e.g. "not good", "never brilliant")
  const negated = analyzeReviewSentiment('This book was not good and definitely not brilliant.', 2);
  assert(negated.score <= 0.0, `Expected negated score <= 0.0, got: ${negated.score}`);
  assert(negated.negativeWords.some((w) => w.word === 'good' || w.word === 'brilliant'), 'Negated positive words should be detected as negative weight');

  // 4.4 Contrastive Conjunction Shift ("great start, but terrible end")
  const contrast = analyzeReviewSentiment('It had a good start, but was ultimately awful, unreadable, and trash.', 2);
  assert(contrast.score <= -0.20, `Expected contrast shift to negative, got: ${contrast.score}`);

  // 4.5 Star Calibration with Empty/Neutral Text
  const starOnly = analyzeReviewSentiment('', 5);
  assert.equal(starOnly.score, 1.0, `Expected star rating 5 to yield score 1.0, got: ${starOnly.score}`);
  assert.equal(starOnly.label, 'positive');

  // 4.6 Double Negation Affirmation ("not without merit", "not without genius")
  const doubleNegMerit = analyzeReviewSentiment('It is not without merit.');
  assert(doubleNegMerit.score > 0.0, `Expected "not without merit" score > 0.0, got: ${doubleNegMerit.score}`);
  assert.equal(doubleNegMerit.label, 'positive');

  const doubleNegGenius = analyzeReviewSentiment('It is not without genius.');
  assert(doubleNegGenius.score > 0.0, `Expected "not without genius" score > 0.0, got: ${doubleNegGenius.score}`);
  assert.equal(doubleNegGenius.label, 'positive');

  // 4.7 Aspect Extraction: "slow-burn" (positive pacing) vs "slow-dragging" (negative pacing)
  const slowBurnReview = analyzeReviewSentiment('A wonderful slow-burn romance with compelling characters.', 5);
  assert(slowBurnReview.aspects.includes('slow-burn'), `Expected slow-burn in aspects, got: ${slowBurnReview.aspects}`);
  assert(!slowBurnReview.aspects.includes('slow-dragging'), `slow-burn must NOT trigger slow-dragging aspect! Got: ${slowBurnReview.aspects}`);
  assert.equal(slowBurnReview.aspectBreakdown['slow-burn'], 'positive');
  assert.equal(slowBurnReview.aspectBreakdown['slow-dragging'], undefined);

  const slowDragReview = analyzeReviewSentiment('A tedious and slow plodding narrative that dragged endlessly.', 1);
  assert(slowDragReview.aspects.includes('slow-dragging'), `Expected slow-dragging in aspects, got: ${slowDragReview.aspects}`);
  assert(!slowDragReview.aspects.includes('slow-burn'), `slow-dragging narrative must NOT trigger slow-burn aspect! Got: ${slowDragReview.aspects}`);
  assert.equal(slowDragReview.aspectBreakdown['slow-dragging'], 'negative');

  // 4.8 Aspect Word Boundary Verification (Substring trigger prevention)
  const exploredText = analyzeReviewSentiment('She explored the quiet streets and mysterious alleys.', 4);
  assert(!exploredText.aspects.includes('world-building'), `"explored" must NOT match "lore" trigger! Got: ${exploredText.aspects}`);

  const upsettingText = analyzeReviewSentiment('An upsetting and distressing mystery drama.', 2);
  assert(!upsettingText.aspects.includes('world-building'), `"upsetting" must NOT match "setting" trigger! Got: ${upsettingText.aspects}`);

  const validSettingText = analyzeReviewSentiment('She explores the rich setting and vast universe.', 5);
  assert(validSettingText.aspects.includes('world-building'), `Standalone "setting" must trigger world-building! Got: ${validSettingText.aspects}`);

  const validLoreText = analyzeReviewSentiment('Fascinating ancient lore and profound mythology.', 5);
  assert(validLoreText.aspects.includes('world-building'), `Standalone "lore" must trigger world-building! Got: ${validLoreText.aspects}`);

  console.log('  ✅ Sentiment analysis, negation lookahead, contrastive shifts, double negation, and aspect isolation verified.');
}

