console.log('Test 1: Metadata Inference & Bayesian Rating');
{
  const fantasyBook = {
    title: 'The Lord of the Rings: The Fellowship of the Ring',
    author: 'J. R. R. Tolkien',
    publisher: 'Del Rey',
    year: 1986,
  };
  const genres = inferGenres(fantasyBook);
  assert(genres.includes('Fantasy'), `Expected Fantasy in genres, got: ${genres}`);

  const tags = inferTags(fantasyBook);
  assert(tags.includes('1980s'), `Expected 1980s in tags, got: ${tags}`);
  assert(tags.includes('high-fantasy'), `Expected high-fantasy in tags, got: ${tags}`);

  const baseline = computeBaselineRating('0345339681');
  assert(baseline >= 3.8 && baseline <= 4.6, `Baseline rating out of range: ${baseline}`);

  const bayesianNoReviews = getCatalogRating('0345339681', []);
  assert.equal(typeof bayesianNoReviews, 'number');

  const bayesianWithReviews = getCatalogRating('0345339681', [
    { rating: 5 }, { rating: 5 }, { rating: 4 },
  ]);
  // Prior = 4.0 (for string), C = 3. Sum = 14, count = 3. (3*4 + 14) / 6 = 26/6 = 4.33
  assert(bayesianWithReviews > 4.1, `Expected blended rating > 4.1, got: ${bayesianWithReviews}`);

  console.log('  ✅ Genre classification, tag inference, and Bayesian rating verified.');
}

