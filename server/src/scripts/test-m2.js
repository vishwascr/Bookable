// 2. Strict Title Similarity Exclusion Tests
// ---------------------------------------------------------------------------
console.log('\nTest 2: Strict Title Similarity Exclusion Invariant');
{
  // Realistic seed books without pre-set tags - tags and genres are inferred dynamically
  const seedInputs = [
    {
      isbn: 'SEED1',
      title: 'The Hobbit',
      author: 'J. R. R. Tolkien',
      aKey: 'jrrtolkien',
      publisher: 'Del Rey',
      year: 1980,
      rating: 4.6,
      dKey: 'hobbit',
    },
    {
      isbn: 'SEED2',
      title: 'A Game of Thrones',
      author: 'George R. R. Martin',
      aKey: 'georgerrmartin',
      publisher: 'Bantam',
      year: 1996,
      rating: 4.5,
      dKey: 'game of thrones',
    },
    {
      isbn: 'SEED3',
      title: 'The Name of the Wind',
      author: 'Patrick Rothfuss',
      aKey: 'patrickrothfuss',
      publisher: 'DAW',
      year: 2007,
      rating: 4.7,
      dKey: 'name of the wind',
    },
  ];

  const seeds = seedInputs.map((b) => ({
    ...b,
    genres: inferGenres(b),
    tags: inferTags(b),
  }));

  // Candidates with identical author, year, publisher, genres, and rating:
  // candA shares major title tokens with Seed 1 ("The Hobbit Quest Return")
  // candB shares NO title tokens with any seed ("The Silmarillion")
  // candC has completely distinct title terminology ("Completely Distinct Lexicon Unrelated")
  // NONE have hardcoded tags - all tags are generated by inferTags(cand) to prove title invariance
  const candA = {
    isbn: 'CAND_A',
    title: 'The Hobbit Quest Return',
    author: 'J. R. R. Tolkien',
    aKey: 'jrrtolkien',
    publisher: 'Del Rey',
    year: 1980,
    genres: ['Fantasy'],
    rating: 4.5,
    dKey: 'hobbit quest return',
  };
  candA.tags = inferTags(candA);

  const candB = {
    isbn: 'CAND_B',
    title: 'The Silmarillion',
    author: 'J. R. R. Tolkien',
    aKey: 'jrrtolkien',
    publisher: 'Del Rey',
    year: 1980,
    genres: ['Fantasy'],
    rating: 4.5,
    dKey: 'silmarillion',
  };
  candB.tags = inferTags(candB);

  const candC = {
    isbn: 'CAND_C',
    title: 'Completely Distinct Lexicon Without Any Overlap',
    author: 'J. R. R. Tolkien',
    aKey: 'jrrtolkien',
    publisher: 'Del Rey',
    year: 1980,
    genres: ['Fantasy'],
    rating: 4.5,
    dKey: 'completely distinct lexicon',
  };
  candC.tags = inferTags(candC);

  // Invariant 1: Ensure inferTags did NOT extract title tokens into tags
  assert(!candA.tags.includes('hobbit'), 'Candidate tags must NOT include title token "hobbit"');
  assert(!candA.tags.includes('quest'), 'Candidate tags must NOT include title token "quest"');
  assert(!candB.tags.includes('silmarillion'), 'Candidate tags must NOT include title token "silmarillion"');

  const featA = computeHeuristicFeatures(candA, seeds);
  const featB = computeHeuristicFeatures(candB, seeds);
  const featC = computeHeuristicFeatures(candC, seeds);

  assert.equal(featA.title, undefined, 'CRITICAL: featA must NOT contain a title feature');
  assert.equal(featB.title, undefined, 'CRITICAL: featB must NOT contain a title feature');
  assert.equal(featC.title, undefined, 'CRITICAL: featC must NOT contain a title feature');

  assert.equal(featA.author, featB.author, 'Author features must be identical');
  assert.equal(featA.genre, featB.genre, 'Genre features must be identical');
  assert.equal(featA.tag, featB.tag, `Tag features must be identical despite title word overlap (A: ${featA.tag}, B: ${featB.tag})`);
  assert.equal(featA.tag, featC.tag, `Tag features must be identical to distinct title candidate (A: ${featA.tag}, C: ${featC.tag})`);
  assert.equal(featA.rating, featB.rating, 'Rating features must be identical');

  const scoreA = scoreCandidate(featA);
  const scoreB = scoreCandidate(featB);
  const scoreC = scoreCandidate(featC);
  assert.equal(scoreA, scoreB, `Scores must be identical despite title differences (A: ${scoreA}, B: ${scoreB})`);
  assert.equal(scoreA, scoreC, `Scores must be identical to zero-overlap title candidate (A: ${scoreA}, C: ${scoreC})`);

  // Test that attempting to supply w_title or title in weights has zero effect
  const scoreWithTitleInjection = scoreCandidate(featA, { ...DEFAULT_THREE_WEIGHTS, title: 0.99, w_title: 0.99 });
  assert.equal(scoreA, scoreWithTitleInjection, 'Injected title weights must have zero effect on scoring');

  console.log('  ✅ Invariant verified: Title similarity has ZERO effect on inferred tags, heuristic features, and scoring.');
}

