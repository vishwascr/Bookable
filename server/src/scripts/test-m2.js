// 3. 3-Seed Recommendation Engine & Diversity Re-Ranking
// ---------------------------------------------------------------------------
console.log('\nTest 3: 3-Seed Recommendation Engine & Diversity Ranking');
{
  // Setup in-memory mock catalog inside engine state
  const eng = engine();
  eng.books = [];
  eng.byIsbn = new Map();
  eng.byAuthor = new Map();
  eng.byGenre = new Map();
  eng.byTag = new Map();
  eng.ready = true;

  const mockCatalog = [
    { isbn: 'S1', title: 'Seed Book One', author: 'Author Alpha', aKey: 'authoralpha', genres: ['Fantasy'], tags: ['magic', 'dragons'], rating: 4.5, dKey: 'seed 1' },
    { isbn: 'S2', title: 'Seed Book Two', author: 'Author Beta', aKey: 'authorbeta', genres: ['Science Fiction'], tags: ['space', 'aliens'], rating: 4.2, dKey: 'seed 2' },
    { isbn: 'S3', title: 'Seed Book Three', author: 'Author Gamma', aKey: 'authorgamma', genres: ['Mystery & Thriller'], tags: ['detective', 'crime'], rating: 4.0, dKey: 'seed 3' },
    // Candidates matching Alpha
    { isbn: 'C1', title: 'Magic Chronicles', author: 'Author Alpha', aKey: 'authoralpha', genres: ['Fantasy'], tags: ['magic'], rating: 4.6, dKey: 'cand 1' },
    { isbn: 'C2', title: 'Dragon Realm', author: 'Author Alpha', aKey: 'authoralpha', genres: ['Fantasy'], tags: ['dragons'], rating: 4.4, dKey: 'cand 2' },
    { isbn: 'C3', title: 'Wizard Tale', author: 'Author Alpha', aKey: 'authoralpha', genres: ['Fantasy'], tags: ['magic'], rating: 4.3, dKey: 'cand 3' },
    // Candidates matching Beta
    { isbn: 'C4', title: 'Star Fleet', author: 'Author Beta', aKey: 'authorbeta', genres: ['Science Fiction'], tags: ['space'], rating: 4.5, dKey: 'cand 4' },
    { isbn: 'C5', title: 'Alien Planet', author: 'Author Beta', aKey: 'authorbeta', genres: ['Science Fiction'], tags: ['aliens'], rating: 4.4, dKey: 'cand 5' },
    // Candidates matching Gamma
    { isbn: 'C6', title: 'Crime Case', author: 'Author Gamma', aKey: 'authorgamma', genres: ['Mystery & Thriller'], tags: ['detective'], rating: 4.2, dKey: 'cand 6' },
    { isbn: 'C7', title: 'Dark Homicide', author: 'Author Gamma', aKey: 'authorgamma', genres: ['Mystery & Thriller'], tags: ['crime'], rating: 4.1, dKey: 'cand 7' },
  ];

  mockCatalog.forEach((b, i) => {
    eng.books.push(b);
    eng.byIsbn.set(b.isbn, i);
    if (!eng.byAuthor.has(b.aKey)) eng.byAuthor.set(b.aKey, []);
    eng.byAuthor.get(b.aKey).push(i);
    for (const g of b.genres) {
      if (!eng.byGenre.has(g)) eng.byGenre.set(g, []);
      eng.byGenre.get(g).push(i);
    }
    for (const t of b.tags) {
      if (!eng.byTag.has(t)) eng.byTag.set(t, []);
      eng.byTag.get(t).push(i);
    }
  });

  const res = recommendThree(['S1', 'S2', 'S3'], DEFAULT_THREE_WEIGHTS, 5);
  assert(res.candidates.length > 0, 'Must return recommendations');
  assert.equal(res.diagnostics.titleExcluded, true, 'Diagnostics must confirm titleExcluded: true');
  assert.equal(res.diagnostics.seedCount, 3, 'Diagnostics seedCount must be 3');

  // Verify candidate fields
  for (const c of res.candidates) {
    assert(c.isbn, 'Candidate must have isbn');
    assert(c.score > 0, 'Candidate score must be > 0');
    assert(c.features, 'Candidate must have features');
    assert.equal(c.features.title, undefined, 'Candidate features must NOT contain title');
    assert(c.bestSeed, 'Candidate must have bestSeed');
    assert(c.matchedSeeds >= 1, 'Candidate must have matchedSeeds');
    assert(c.explanation, 'Candidate must have explanation');
  }

  // Verify diversity: top picks should not all belong to one seed when other seeds have strong matches
  const bestSeedsPicked = res.candidates.map((c) => c.bestSeed);
  const distinctSeedsInTopPicks = new Set(bestSeedsPicked);
  assert(distinctSeedsInTopPicks.size >= 2, `Expected diverse seed representation in top 5 picks, got: ${[...distinctSeedsInTopPicks]}`);

  // Test error handling: 2 seeds or unknown seed
  assert.throws(() => recommendThree(['S1', 'S2']), /Exactly 3 seed books/);
  assert.throws(() => recommendThree(['S1', 'S2', 'UNKNOWN_ISBN']), /Seed book not found/);

  console.log('  ✅ 3-Seed recommendation pipeline and diversity re-ranking verified.');
}

